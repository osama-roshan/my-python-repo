# using built-in functions for list

marks = [ 40,39,58,72,84,90]
print(marks)

# Length of marks list
a = len(marks)
print(f"The lenght of marks {a}")

# max number in marks list
maxi = max(marks)
print(f"Max of marks list = {maxi}")

# min number in marks list 

mini = min(marks)
print(f"Min of marks list = {mini}")


#sum of all numbers in marks list 

total = sum(marks)
print(f"total of marks list no = {total}")


